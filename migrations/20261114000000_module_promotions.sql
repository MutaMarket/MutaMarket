-- Promoted modules: a donation with a "promote <item id>" reason buys the
-- module days at the top of the for-sale browser's default order. The
-- end of the paid time lives on the module so the listing query reads it
-- without a join; the partial index keeps the handful of promoted rows
-- one probe away.
ALTER TABLE modules ADD COLUMN promoted_until timestamp with time zone;

CREATE INDEX modules_promoted_until_index ON modules USING btree (promoted_until)
    WHERE promoted_until IS NOT NULL;

-- Which donation bought how many days for which module, one row per
-- donation: the record behind the running total above.
CREATE TABLE module_promotions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id bigint NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    donation_id bigint NOT NULL UNIQUE REFERENCES donations(id) ON DELETE CASCADE,
    days integer NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX module_promotions_module_id_index ON module_promotions USING btree (module_id);
